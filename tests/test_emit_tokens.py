def copy_tree(tmp_path):
    root = tmp_path / "out"
    for f in emit_tokens.FILES.values():
        (root / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(ROOT / f, root / f)
    return root


def test_s184_a_changed_token_fails_check_and_names_the_file(tmp_path, capsys):
    root = copy_tree(tmp_path)
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    t["color"]["primary"]["$value"] = "#0055CC"
    changed = tmp_path / "tokens.json"
    changed.write_text(json.dumps(t), encoding="utf-8")
    assert emit_tokens.main(["--check", "--tokens", str(changed), "--out", str(root)]) == 1
    err = capsys.readouterr().err
    assert "ui/android/theme/Theme.kt" in err and "ui/ios/Sources/ShipQuickUI/Tokens.swift" in err
    assert emit_tokens.main(["--tokens", str(changed), "--out", str(root)]) == 0  # regenerate
    assert emit_tokens.main(["--check", "--tokens", str(changed), "--out", str(root)]) == 0
    assert "0055CC" in (root / "ui/android/theme/Theme.kt").read_text(encoding="utf-8")


