"""Story #184 (S6): design/tokens.json drives Theme.kt and Tokens.swift. A golden file per platform,
no token dropped, and a token change without regenerating fails --check."""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import emit_tokens  # noqa: E402

TOKENS = ROOT / "design" / "tokens.json"
GOLDEN = ROOT / "tests" / "golden"


def test_s184_theme_kt_matches_its_golden_file():
    assert emit_tokens.render(TOKENS)["kt"] == (GOLDEN / "Theme.kt.golden").read_text(encoding="utf-8")


def test_s184_tokens_swift_matches_its_golden_file():
    assert emit_tokens.render(TOKENS)["swift"] == (GOLDEN / "Tokens.swift.golden").read_text(encoding="utf-8")


def test_s184_committed_files_are_current():
    assert emit_tokens.main(["--check"]) == 0


def leaf_paths(node, path=()):
    for k, v in node.items():
        if k.startswith("$"):
            continue
        if isinstance(v, dict) and "$value" not in v:
            yield from leaf_paths(v, path + (k,))
        else:
            yield path + (k,), v["$value"]


def cap(s):
    return s[0].upper() + s[1:]


def test_s184_every_token_reaches_both_outputs():
    out = emit_tokens.render(TOKENS)
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    n = 0
    for path, value in leaf_paths(t):
        n += 1
        name = path[-1]
        if path[:2] == ("feel", "touchTarget"):
            own = out["kt"] if name == "android" else out["swift"]
            assert str(value)[:-2] in own, path  # 48dp -> 48
        elif path[:2] == ("feel", "motion"):
            assert (f"easing{cap(name)}" if path[2] == "easing" else f"duration{cap(name)}") in out["kt"], path
            assert (name if path[2] == "easing" else f"duration{cap(name)}") in out["swift"], path
        elif path[:2] == ("feel", "haptics"):
            assert value["android"] in out["kt"] and value["ios"].split(".")[1] in out["swift"], path
        elif path == ("typography", "fontFamily"):
            continue  # system-ui: each platform's own font, FontFamily.Default and Font.system
        else:
            assert name in out["kt"] and name in out["swift"], path
    assert n > 30


def test_s184_both_outputs_say_they_are_generated():
    out = emit_tokens.render(TOKENS)
    for k in ("kt", "swift"):
        assert out[k].startswith("// GENERATED by scripts/emit_tokens.py"), k


def copy_tree(tmp_path):
    root = tmp_path / "out"
    for f in emit_tokens.FILES.values():
        (root / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(ROOT / f, root / f)
    return root


def test_s184_a_changed_token_fails_check_and_names_the_file(tmp_path, capsys):
    root = copy_tree(tmp_path)
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    t["color"]["primary"]["$value"] = "#0055CC"
    changed = tmp_path / "tokens.json"
    changed.write_text(json.dumps(t), encoding="utf-8")
    assert emit_tokens.main(["--check", "--tokens", str(changed), "--out", str(root)]) == 1
    err = capsys.readouterr().err
    assert "ui/android/theme/Theme.kt" in err and "ui/ios/Sources/ShipQuickUI/Tokens.swift" in err
    assert emit_tokens.main(["--tokens", str(changed), "--out", str(root)]) == 0  # regenerate
    assert emit_tokens.main(["--check", "--tokens", str(changed), "--out", str(root)]) == 0
    assert "0055CC" in (root / "ui/android/theme/Theme.kt").read_text(encoding="utf-8")


def test_s184_an_unknown_token_group_fails_instead_of_being_dropped(tmp_path, capsys):
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    t["elevation"] = {"low": {"$value": "1dp"}}
    bad = tmp_path / "tokens.json"
    bad.write_text(json.dumps(t), encoding="utf-8")
    assert emit_tokens.main(["--check", "--tokens", str(bad), "--out", str(tmp_path)]) == 2
    assert "elevation" in capsys.readouterr().err


def test_s184_a_missing_file_fails_check(tmp_path):
    assert emit_tokens.main(["--check", "--out", str(tmp_path)]) == 1


def test_s184_haptic_names_are_checked(tmp_path, capsys):
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    t["feel"]["haptics"]["press"]["$value"]["ios"] = "buzz.hard"
    bad = tmp_path / "tokens.json"
    bad.write_text(json.dumps(t), encoding="utf-8")
    assert emit_tokens.main(["--tokens", str(bad), "--out", str(tmp_path)]) == 2
    assert "feel.haptics.press.ios" in capsys.readouterr().err


def test_s184_the_wiring_compiles_the_generated_files():
    assert '"theme"' in (ROOT / "ui/android/build.gradle.kts").read_text(encoding="utf-8")
    assert "Sources/ShipQuickUI" in (ROOT / "ui/ios/Package.swift").read_text(encoding="utf-8")
