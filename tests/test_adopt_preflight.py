"""Story #446: a child's bump is checked locally the way its CI will check it. adopt.sh installs the git hooks when the ShipQuick
hooks are configured and the hooks folder is empty; `--check` reports hooks not installed, commit subjects over 72 characters
since the base, and environments at the caller's milestone; the session-start hook warns about uninstalled hooks.
Real git in a tmp child, a stand-in `pre-commit`, a stub gh. Generic: no child is named."""
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_adopt import FAKE_PRECOMMIT, HEAD, add_fake_submodule, adopt, gh, with_origin  # noqa: E402,F401

ROOT = Path(__file__).resolve().parent.parent
STATE = ROOT / "plugin" / "hooks" / "hooks_state.py"
SESSION = ROOT / "plugin" / "hooks" / "session_start.py"


def git(c, *a):
    return subprocess.run(["git", *a], cwd=c, capture_output=True, text=True, check=True).stdout


@pytest.fixture
def child(tmp_path):
    c = tmp_path / "kid"
    (c / ".github" / "workflows").mkdir(parents=True)
    git(tmp_path, "init", "-q", "-b", "dev", str(c))
    git(c, "config", "user.email", "t@example.com")
    git(c, "config", "user.name", "T")
    (c / ".github" / "workflows" / "ci.yml").write_text("name: Kid CI\non:\n  push:\n", encoding="utf-8")
    return c


def hooks_dir(c):
    return Path(git(c, "rev-parse", "--absolute-git-dir").strip()) / "hooks"


def state(c):
    p = subprocess.run([sys.executable, str(STATE), str(c)], capture_output=True, text=True)
    return p.returncode, p.stdout.strip()


def real_hooks(c):
    h = hooks_dir(c)
    h.mkdir(exist_ok=True)
    for t in ("pre-commit", "commit-msg"):
        (h / t).write_text("#!/usr/bin/env bash\n# File generated by pre-commit\n", encoding="utf-8")


def ready(child, gh, milestone=None):
    """Adopted, with hooks installed by adopt itself, as a real child would be."""
    with_origin(child)
    r = adopt(child, *(["--milestone", milestone] if milestone else []), env=gh)
    assert r.returncode == 0, r.stderr
    add_fake_submodule(child, HEAD)
    return child


# ---- the one shared answer: plugin/hooks/hooks_state.py ----
def test_state_no_config_is_not_configured_and_exit_0(child):
    assert state(child) == (0, "not-configured")


def test_state_configured_with_an_empty_hooks_folder_is_missing_and_exit_1(child):
    adopt(child, precommit=False)
    assert (child / ".pre-commit-config.yaml").exists()
    assert state(child) == (1, "missing")


def test_state_one_hook_missing_is_still_missing(child):
    adopt(child, precommit=False)
    real_hooks(child)
    (hooks_dir(child) / "commit-msg").unlink()
    assert state(child) == (1, "missing")


def test_state_a_sample_hook_is_not_an_installed_hook(child):
    adopt(child, precommit=False)
    h = hooks_dir(child); h.mkdir(exist_ok=True)
    (h / "commit-msg").write_text("#!/bin/sh\n# an unrelated hook\n", encoding="utf-8")
    (h / "pre-commit").write_text("#!/bin/sh\n# an unrelated hook\n", encoding="utf-8")
    assert state(child) == (1, "missing")


def test_state_installed_is_exit_0(child):
    adopt(child, precommit=False)
    real_hooks(child)
    assert state(child) == (0, "installed")


def test_state_pre_commit_feature_off_needs_no_hooks(child):
    adopt(child, precommit=False)
    f = json.loads((child / ".shipquick" / "features.json").read_text(encoding="utf-8"))
    f["features"]["pre-commit"]["on"] = False
    (child / ".shipquick" / "features.json").write_text(json.dumps(f), encoding="utf-8")
    assert state(child) == (0, "off")


def test_state_not_a_repo_is_exit_2_never_ok(tmp_path):
    (tmp_path / "x").mkdir()
    (tmp_path / "x" / ".pre-commit-config.yaml").write_text("repos:\n  - repo: local\n    hooks:\n      - entry: bash scripts/check_local.sh\n", encoding="utf-8")
    code, out = state(tmp_path / "x")
    assert code == 2 and out != "installed"


# ---- adopt.sh installs the hooks ----
def test_adopt_installs_the_hooks_when_configured_and_the_folder_is_empty(child):
    r = adopt(child)
    assert r.returncode == 0, r.stderr
    assert state(child) == (0, "installed")
    assert "installed  git hooks" in r.stdout


def test_a_second_adopt_says_the_hooks_are_there_and_changes_nothing(child):
    adopt(child)
    before = {p.name: p.read_bytes() for p in hooks_dir(child).iterdir()}
    r = adopt(child)
    assert "unchanged git hooks" in r.stdout
    assert {p.name: p.read_bytes() for p in hooks_dir(child).iterdir()} == before


def test_adopt_with_pre_commit_off_installs_no_hooks(child):
    (child / ".shipquick").mkdir()
    (child / ".shipquick" / "features.json").write_text(json.dumps({"version": 1, "features": {"pre-commit": {"on": False, "default": True}}}), encoding="utf-8")
    r = adopt(child)
    assert r.returncode == 0 and not hooks_dir(child).exists() or not list(hooks_dir(child).glob("commit-msg"))
    assert "git hooks" not in r.stdout or "skipped" in r.stdout


def test_a_failing_pre_commit_is_said_in_one_line_and_adopt_still_finishes(child, tmp_path):
    bad = tmp_path / "bad"; bad.mkdir()
    (bad / "pre-commit").write_text('#!/usr/bin/env bash\necho "boom" >&2\nexit 1\n', encoding="utf-8"); (bad / "pre-commit").chmod(0o755)
    env = {**os.environ, "PATH": f"{bad}:{os.environ['PATH']}"}
    r = adopt(child, env=env, precommit=False)
    assert r.returncode == 0, r.stderr
    assert "could not install the git hooks" in r.stdout and "pre-commit install" in r.stdout
    assert state(child) == (1, "missing")


# ---- --check ----
def test_check_fails_when_the_hooks_are_configured_but_not_installed(child, gh):
    ready(child, gh)
    for t in hooks_dir(child).glob("*"):
        t.unlink()
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 1
    assert "not adopted: the git hooks are configured but not installed" in r.stdout and "pre-commit install" in r.stdout


def test_check_passes_when_the_hooks_are_installed(child, gh):
    ready(child, gh)
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 0, (r.stdout, r.stderr)


def commit(c, subject):
    (c / "f.txt").write_text(subject, encoding="utf-8")
    git(c, "add", "f.txt")   # not -A: the fake submodule is only a gitlink, `add -A` would drop it
    git(c, "commit", "-q", "-m", subject)


def with_base(c):
    """origin/dev at the current commit, so `since the base` means the commits made after this."""
    git(c, "update-ref", "refs/remotes/origin/dev", "HEAD")


def test_check_names_a_commit_subject_over_72_since_the_base(child, gh):
    ready(child, gh)
    with_base(child)
    long = "chore(knowledge): " + "x" * 63   # 81
    commit(child, long)
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 1
    assert "not adopted: commit subject over 72 characters (81)" in r.stdout and long[:40] in r.stdout


def test_check_accepts_a_72_character_subject_and_ignores_commits_before_the_base(child, gh):
    ready(child, gh)
    commit(child, "chore: " + "y" * 80)    # before the base: not this branch's
    with_base(child)
    commit(child, "chore: " + "z" * 65)    # exactly 72
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 0, (r.stdout, r.stderr)


def test_check_without_a_base_branch_skips_the_subject_check(child, gh):
    ready(child, gh)
    commit(child, "chore: " + "y" * 90)
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 0, (r.stdout, r.stderr)


def test_check_runs_environments_at_the_callers_milestone(child, gh):
    ready(child, gh, milestone="D1")   # the CLAUDE.md template starts with placeholder links
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 1
    assert "not adopted: environments:" in r.stdout and "empty or placeholder" in r.stdout and "past D1" in r.stdout


def test_check_with_no_milestone_line_uses_the_ci_default_d1(child, gh):
    # CI gives a caller with no `milestone:` line D1 (checks.yml); --check must say the same, never skip (Miraya#2)
    with_origin(child)
    assert adopt(child, env=gh, d0=False).returncode == 0
    add_fake_submodule(child, HEAD)
    assert "milestone:" not in (child / ".github/workflows/shipquick-call.yml").read_text(encoding="utf-8")
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 1
    assert "not adopted: environments:" in r.stdout and "past D1" in r.stdout


def test_check_environments_passes_once_both_links_are_filled(child, gh):
    ready(child, gh, milestone="D1")
    md = child / "CLAUDE.md"
    t = md.read_text(encoding="utf-8")
    import re
    t = re.sub(r"^- Dev link:.*$", "- Dev link: https://dev.example.test", t, flags=re.M)
    t = re.sub(r"^- Production link:.*$", "- Production link: https://prod.example.test", t, flags=re.M)
    md.write_text(t, encoding="utf-8")
    r = adopt(child, "--check", env=gh)
    assert r.returncode == 0, (r.stdout, r.stderr)


def test_check_at_milestone_d0_does_not_ask_for_links(child, gh):
    ready(child, gh, milestone="D0")
    assert adopt(child, "--check", env=gh).returncode == 0


# ---- the session-start warning ----
def session(c):
    env = {**os.environ}
    env.pop("CLAUDE_PROJECT_DIR", None)
    p = subprocess.run([sys.executable, str(SESSION)], input=json.dumps({"cwd": str(c)}), capture_output=True, text=True, cwd=c, env=env, timeout=10)
    assert p.returncode == 0
    return json.loads(p.stdout)["hookSpecificOutput"]["additionalContext"]


def test_session_start_warns_once_when_hooks_are_configured_but_not_installed(child):
    adopt(child, precommit=False)
    ctx = session(child)
    assert ctx.count("git hooks are configured but not installed") == 1 and "pre-commit install" in ctx


def test_session_start_is_quiet_when_installed_or_not_configured(child):
    assert "not installed" not in session(child)     # no config
    adopt(child, precommit=False)
    real_hooks(child)
    assert "not installed" not in session(child)


