"""Story #222 (S5g): one Swift struct per ui/components/<Name>/<Name>.contract.json, written into ui/ios/.
A contract field renamed without regenerating fails --check and names the struct file."""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import emit_contracts  # noqa: E402

SRC = ROOT / "ui" / "components"
OUT = ROOT / "ui" / "ios" / "Sources" / "ShipQuickUI" / "Contracts"

# A made-up contract that uses every prop kind the generator maps, plus the names it must rewrite.
SAMPLE = {
    "name": "sample-card",
    "baseTarget": "container",
    "types": {},
    "core": {
        "title": {"type": {"kind": "string"}, "doc": "The heading"},
        "count": {"type": {"kind": "number"}, "optional": True},
        "tone": {"type": {"kind": "enum", "values": ["calm", "loud", "2x"]}, "optional": True},
        "isOn": {"type": {"kind": "boolean"}},
        "onSelect": {"type": {"kind": "fn", "args": [{"kind": "string"}]}, "optional": True},
        "onOpen": {"type": {"kind": "fn", "args": []}},
        "content": {"type": {"kind": "content"}},
        "tags": {"type": {"kind": "array", "of": {"kind": "string"}}, "optional": True},
    },
    "platforms": {
        "ios": {
            "in": {"type": {"kind": "named", "name": "ClosedRange<Strideable>"}},
            "selection": {"type": {"kind": "named", "name": "Binding<SelectionValue?>"}, "optional": True},
        },
        "android": {"state": {"type": {"kind": "named", "name": "TextFieldState"}}},
    },
    "webOnly": [{"name": "href", "reason": "a web link"}],
    "sameMeaning": {"onSelect": "a tap on a row"},
}


def components_with(tmp_path, contracts):
    root = tmp_path / "components"
    for c in contracts:
        d = root / c["name"]
        d.mkdir(parents=True)
        (d / f"{c['name']}.contract.json").write_text(json.dumps(c), encoding="utf-8")
    return root


def test_s222_the_committed_structs_are_current_with_the_contracts():
    assert emit_contracts.main(["--check"]) == 0


def test_s222_every_contract_has_a_struct_file():
    contracts = sorted(p.parent.name for p in SRC.glob("*/*.contract.json"))
    assert len(contracts) > 50
    files = {p.name for p in OUT.glob("*.swift")}
    for name in contracts:
        assert f"{emit_contracts.pascal(name)}.swift" in files, name


def test_s222_every_prop_kind_maps_to_a_swift_type(tmp_path):
    files = emit_contracts.render(components_with(tmp_path, [SAMPLE]))
    assert list(files) == ["SampleCard.swift"]
    swift = files["SampleCard.swift"]
    assert swift.startswith("// GENERATED by scripts/emit_contracts.py")
    assert "import SwiftUI" in swift
    assert "public struct SampleCardProps {" in swift
    assert "/// The heading\n    public var title: String\n" in swift
    assert "public var count: Double?" in swift
    assert 'public enum SampleCardTone: String, CaseIterable {\n    case calm = "calm"\n    case loud = "loud"\n    case v2x = "2x"\n}' in swift
    assert "public var tone: SampleCardTone?" in swift
    assert "public var isOn: Bool" in swift
    assert "/// Same meaning: a tap on a row\n    public var onSelect: ((String) -> Void)?" in swift
    assert "public var onOpen: () -> Void" in swift and "onOpen: @escaping () -> Void" in swift
    assert "public var content" not in swift and "// Content slots, taken as view builders: content" in swift
    assert "public var tags: [String]?" in swift
    assert "/// Contract type: ClosedRange<Strideable>\n    public var `in`: ClosedRange<Double>" in swift
    assert "self.`in` = `in`" in swift
    assert "public var selection: Binding<AnyHashable?>?" in swift
    assert "TextFieldState" not in swift, "Android props stay out of the Swift struct"
    assert "// Web only, not here: href (a web link)" in swift
    assert "// Base props attach to: container" in swift


def test_s222_the_folder_names_the_struct_when_two_contracts_share_an_inner_name(tmp_path):
    root = components_with(tmp_path, [SAMPLE])
    twin = root / "tooltip-card"  # a second folder whose contract keeps the inner name "sample-card"
    twin.mkdir()
    (twin / "tooltip-card.contract.json").write_text(json.dumps(SAMPLE), encoding="utf-8")
    files = emit_contracts.render(root)
    assert sorted(files) == ["SampleCard.swift", "TooltipCard.swift"]
    assert "public struct TooltipCardProps {" in files["TooltipCard.swift"]
    assert "public enum TooltipCardTone" in files["TooltipCard.swift"]
    assert "// Contract name: sample-card." in files["TooltipCard.swift"]


def test_s222_a_record_type_becomes_a_nested_struct_and_an_unknown_kind_fails_by_name(tmp_path):
    c = json.loads(json.dumps(SAMPLE))
    c["core"]["badge"] = {"type": {"kind": "record", "fields": {"text": {"type": {"kind": "string"}}}}}
    swift = emit_contracts.render(components_with(tmp_path, [c]))["SampleCard.swift"]
    assert "public struct SampleCardBadge {" in swift and "public var badge: SampleCardBadge" in swift
    c["core"]["label"] = {"type": {"kind": "textOrBoolean"}}
    try:
        emit_contracts.render(components_with(tmp_path / "two", [c]))
    except emit_contracts.ContractError as e:
        assert "sample-card" in str(e) and "label" in str(e) and "textOrBoolean" in str(e)
    else:
        raise AssertionError("an unknown kind must fail, not be dropped")


def copy_tree(tmp_path):
    root, out = tmp_path / "components", tmp_path / "Contracts"
    shutil.copytree(SRC, root)
    shutil.copytree(OUT, out)
    return root, out


def test_s222_a_renamed_contract_field_fails_check_and_names_the_struct_file(tmp_path, capsys):
    root, out = copy_tree(tmp_path)
    assert emit_contracts.main(["--check", "--root", str(root), "--out", str(out)]) == 0
    path = root / "Button" / "Button.contract.json"
    c = json.loads(path.read_text(encoding="utf-8"))
    c["core"]["title"] = c["core"].pop("label")
    path.write_text(json.dumps(c), encoding="utf-8")
    assert emit_contracts.main(["--check", "--root", str(root), "--out", str(out)]) == 1
    assert "Button.swift" in capsys.readouterr().out
    assert emit_contracts.main(["--root", str(root), "--out", str(out)]) == 0  # regenerate
    assert "public var title: String" in (out / "Button.swift").read_text(encoding="utf-8")
    assert emit_contracts.main(["--check", "--root", str(root), "--out", str(out)]) == 0


def test_s222_a_removed_contract_leaves_a_stale_struct_that_check_names(tmp_path, capsys):
    root, out = copy_tree(tmp_path)
    shutil.rmtree(root / "Chip")
    assert emit_contracts.main(["--check", "--root", str(root), "--out", str(out)]) == 1
    assert "Chip.swift" in capsys.readouterr().out
    assert emit_contracts.main(["--root", str(root), "--out", str(out)]) == 0
    assert not (out / "Chip.swift").exists()


def test_s222_check_local_and_ci_run_the_check():
    assert 'emit_contracts.py" --check' in (ROOT / "scripts" / "check_local.sh").read_text(encoding="utf-8")
    assert "python3 scripts/emit_contracts.py --check" in (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
