# story #446: adopt.sh installs the git hooks itself and --check wants them installed. Every test runs with a stand-in `pre-commit`
# that writes the hook files the way the real one does, so no test needs the real tool or the network.
FAKE_PRECOMMIT = Path(tempfile.mkdtemp(prefix="fake-precommit-"))
(FAKE_PRECOMMIT / "pre-commit").write_text(
    '#!/usr/bin/env bash\n[ "$1" = install ] || exit 0\nh="$(git rev-parse --git-path hooks)"; mkdir -p "$h"\n'
    'for t in pre-commit commit-msg pre-push prepare-commit-msg; do printf \'#!/usr/bin/env bash\\n# File generated by pre-commit\\n\' > "$h/$t"; chmod +x "$h/$t"; done\n', encoding="utf-8")
(FAKE_PRECOMMIT / "pre-commit").chmod(0o755)


def adopt(child, *args, env=None, settings=None, ci=False, precommit=True, d0=True):
    # --check reads a caller with no `milestone:` line as D1 (as CI does), so a test that is not about links adopts at D0
    if d0 and "--check" not in args and "--milestone" not in args:
        args = (*args, "--milestone", "D0")
    e = dict(os.environ if env is None else env)
    if precommit:
        e["PATH"] = f"{FAKE_PRECOMMIT}:{e['PATH']}"
    e["SHIPQUICK_CLAUDE_SETTINGS"] = str(settings or PONYTAIL_ON)
    e.pop("CI", None)   # a real CI runner sets CI; a test sets it on purpose with ci=True
    if ci:
        e["CI"] = "1"
    return subprocess.run(["bash", str(ADOPT), str(child), *args], capture_output=True, text=True, env=e)


def snapshot(child):
    return {str(p.relative_to(child)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(child.rglob("*")) if p.is_file() and ".git" not in p.relative_to(child).parts}


