    '#!/usr/bin/env bash\n[ "$1" = install ] || exit 0\nh="$(git rev-parse --git-path hooks)"; mkdir -p "$h"\n'
    # story #479: like the real hooks, a stand-in hook stops the commit when the branch has no config
