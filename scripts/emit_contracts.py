"""Story #222 (S5g): one Swift struct per ui/components/<Name>/<Name>.contract.json (rule 38, ADR-012).

Writes ui/ios/Sources/ShipQuickUI/Contracts/<Name>.swift: `<Name>Props` holds the contract's core props and its
`platforms.ios` props as typed fields, one nested enum per enum prop, one struct per record and per `types` entry.
The Swift package compiles the folder with the templates, so a type that is not real Swift fails CI.
Content slots are not fields (SwiftUI takes content as a view builder); they are listed in a comment, so a renamed
slot still changes the file. Android props stay out: the Kotlin twin is its own story.

The type map follows Astryx `packages/native/src/contract/generateSwift.ts` (Meta, MIT), read at the commit in
ui/UPSTREAM.md; written here in Python, nothing copied. One thing a contract cannot say lives here: GENERIC,
the concrete type that stands in for a generic placeholder (`Binding<SelectionValue>`), because a stored field
needs a real type. Stdlib only.

Usage: python3 scripts/emit_contracts.py            write the structs (and remove one whose contract is gone)
       python3 scripts/emit_contracts.py --check    exit 1, naming each file, when one is missing, stale or extra
       python3 scripts/emit_contracts.py [--check] --root <components> --out <dir>   other folders (tests)
"""
import argparse
import json
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
SRC = KIT / "ui" / "components"
OUT = KIT / "ui" / "ios" / "Sources" / "ShipQuickUI" / "Contracts"
HEADER = ("// GENERATED by scripts/emit_contracts.py from ui/components/{name}/{name}.contract.json (story #222). Do not edit.\n"
          "// Change the contract, then run: python3 scripts/emit_contracts.py\n")
SWIFT_KEYWORDS = set("associatedtype class deinit enum extension fileprivate func import init inout internal let open operator "
                     "private precedencegroup protocol public rethrows static struct subscript typealias var break case catch "
                     "continue default defer do else fallthrough for guard if in repeat return throw switch where while Any as "
                     "await false is nil self Self super throws true try".split())
# shortcut: a fixed table of placeholder -> stored type; add a row when a contract names a new generic placeholder.
# A protocol with associated types needs `any`, a generic parameter needs one concrete type.
GENERIC = {"SelectionValue": "AnyHashable", "Hashable": "AnyHashable", "ID": "AnyHashable", "Data.Element": "AnyHashable",
           "Strideable": "Double", "BinaryFloatingPoint": "Double",
           "RandomAccessCollection": "any RandomAccessCollection", "Transferable": "any Transferable"}
SIMPLE = {"string": "String", "number": "Double", "boolean": "Bool", "icon": "Image"}


class ContractError(Exception):
    pass


def camel(text):
    return re.sub(r"[-_ ]+([A-Za-z0-9])", lambda m: m.group(1).upper(), text)


def pascal(text):
    s = camel(text)
    return s[0].upper() + s[1:]


def ident(name):
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def case_name(value):
    name = camel(re.sub(r"[^A-Za-z0-9_-]", "-", value))
    return ident(f"v{name}" if re.match(r"^[0-9]", name) else name or "empty")


def concrete(name):
    """A contract's named type as one Swift can store: placeholders replaced, whole words only."""
    for k, v in GENERIC.items():
        name = re.sub(rf"(?<![\w.]){re.escape(k)}(?![\w.])", v, name)
    return name


class Writer:
    """Turns prop types into Swift type names; collects the enum and struct declarations they need."""

    def __init__(self, component):
        self.component, self.decls = component, []

    def type(self, owner, prop, t):
        kind = t["kind"]
        if kind in SIMPLE:
            return SIMPLE[kind]
        if kind == "enum":
            name = f"{owner}{pascal(prop)}"
            cases = "\n".join(f'    case {case_name(v)} = "{v}"' for v in t["values"])
            self.decls.append(f"public enum {name}: String, CaseIterable {{\n{cases}\n}}")
            return name
        if kind == "numberEnum":
            name = f"{owner}{pascal(prop)}"
            raw = "Int" if all(isinstance(v, int) for v in t["values"]) else "Double"
            cases = "\n".join(f"    case v{str(v).replace('-', 'Minus').replace('.', '_')} = {v}" for v in t["values"])
            self.decls.append(f"public enum {name}: {raw}, CaseIterable {{\n{cases}\n}}")
            return name
        if kind == "array":
            return f"[{self.type(owner, prop, t['of'])}]"
        if kind == "record":
            name = f"{owner}{pascal(prop)}"
            self.decls.append(self.struct(name, t["fields"]))
            return name
        if kind == "fn":
            return f"({', '.join(self.type(owner, f'{prop}Arg{i}', a) for i, a in enumerate(t.get('args', [])))}) -> Void"
        if kind == "named":
            return concrete(t["name"])
        raise ContractError(f"{self.component}: prop {prop!r} has kind {kind!r}, which this emitter does not map")

    def fields(self, owner, props, docs=None):
        """(doc lines, declaration, init parameter, assignment) per stored prop. Content slots are skipped."""
        out = []
        for name, spec in props.items():
            t = spec["type"]
            if t["kind"] == "content":
                continue
            base = self.type(owner, name, t)
            optional = bool(spec.get("optional"))
            if optional and not base.endswith("?"):
                base = f"({base})?" if t["kind"] == "fn" else f"{base}?"
            doc = [f"/// {spec['doc']}"] if spec.get("doc") else []
            if docs and name in docs:
                doc.append(f"/// Same meaning: {docs[name]}")
            if t["kind"] == "named" and base != t["name"]:
                doc.append(f"/// Contract type: {t['name']}")
            esc = "@escaping " if t["kind"] == "fn" and not optional else ""
            out.append((doc, f"public var {ident(name)}: {base}",
                        f"{ident(name)}: {esc}{base}{' = nil' if optional else ''}", f"self.{ident(name)} = {ident(name)}"))
        return out

    def struct(self, name, props, extra=(), docs=None, owner=None):
        """`owner` prefixes the nested enum and struct names (ButtonVariant, not ButtonPropsVariant)."""
        fields = self.fields(owner or name, props, docs)
        lines = [f"public struct {name} {{"] + [f"    // {e}" for e in extra]
        for doc, decl, _, _ in fields:
            lines += [f"    {d}" for d in doc] + [f"    {decl}"]
        lines.append(f"    public init({', '.join(p for _, _, p, _ in fields)}) {{")
        lines += [f"        {a}" for _, _, _, a in fields] + ["    }", "}"]
        return "\n".join(lines)


def render_one(folder, contract):
    """The folder name names the file, the struct and the nested types: two contracts may share an inner `name`."""
    name, struct_name = folder, f"{pascal(folder)}Props"
    w = Writer(name)
    types = [w.struct(pascal(t), fields) for t, fields in contract.get("types", {}).items()]
    props = {**contract["core"], **contract.get("platforms", {}).get("ios", {})}
    extra = [f"Base props attach to: {contract['baseTarget']}."]
    if contract["name"] != folder:
        extra.insert(0, f"Contract name: {contract['name']}.")
    slots = [n for n, s in props.items() if s["type"]["kind"] == "content"]
    if slots:
        extra.append(f"Content slots, taken as view builders: {', '.join(slots)}")
    for web in contract.get("webOnly", []):
        extra.append(f"Web only, not here: {web['name']} ({web['reason']})")
    body = w.struct(struct_name, props, extra, contract.get("sameMeaning") or {}, owner=pascal(name))
    parts = types + w.decls + [body]
    return HEADER.format(name=name) + "import SwiftUI\n\n" + "\n\n".join(parts) + "\n"


def render(root):
    """file name -> Swift text, one per <dir>/<dir>.contract.json under root, sorted."""
    files = {}
    for d in sorted(p for p in Path(root).iterdir() if p.is_dir()):
        c = d / f"{d.name}.contract.json"
        if c.exists():
            files[f"{pascal(d.name)}.swift"] = render_one(d.name, json.loads(c.read_text(encoding="utf-8")))
    return files


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", type=Path, default=SRC, help="folder with one subfolder per component")
    ap.add_argument("--out", type=Path, default=OUT, help="folder the Swift files are written to")
    a = ap.parse_args(argv)
    try:
        files = render(a.root)
    except ContractError as e:
        print(f"ui contracts: {e}")
        return 2
    have = {p.name for p in a.out.glob("*.swift")} if a.out.is_dir() else set()
    stale = sorted(f for f in files if f not in have or (a.out / f).read_text(encoding="utf-8") != files[f])
    extra = sorted(have - set(files))
    if a.check:
        for f in stale:
            print(f"ui contracts: {a.out / f} is missing or stale; run python3 scripts/emit_contracts.py")
        for f in extra:
            print(f"ui contracts: {a.out / f} has no contract; run python3 scripts/emit_contracts.py")
        print("ui contracts OK" if not stale and not extra else f"{len(stale) + len(extra)} struct file(s) out of date")
        return 1 if stale or extra else 0
    a.out.mkdir(parents=True, exist_ok=True)
    for f in stale:
        (a.out / f).write_text(files[f], encoding="utf-8")
    for f in extra:
        (a.out / f).unlink()
    print(f"wrote {len(stale)} and removed {len(extra)} of {len(files)} struct file(s) in {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
