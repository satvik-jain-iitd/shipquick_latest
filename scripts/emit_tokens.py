"""Story #184 (S6): one design/tokens.json drives both native themes (rule 38, ADR-012).

Writes ui/android/theme/Theme.kt (Compose Material 3) and ui/ios/Sources/ShipQuickUI/Tokens.swift (SwiftUI),
plus a golden copy of each in tests/golden/. The `feel` group (touch target, motion, haptics) is the shared part;
colour and type follow each platform's own idiom. Stdlib only.

A token this script does not know fails the run, so no token is dropped silently.
The dark colours are derived here (the tokens file has one set): dark swaps background with onSurface and
primary with onPrimary, and mixes surface, muted text and outline from those. A child that wants other dark colours
changes this one function, not the generated files.

Usage: python3 scripts/emit_tokens.py                 write the four files
       python3 scripts/emit_tokens.py --check         exit 1, naming the file, when one is missing or stale
       python3 scripts/emit_tokens.py --tokens <file> --out <dir>   another tokens file, another root (tests)
"""
import argparse
import json
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
FILES = {  # key -> path under the output root
    "kt": "ui/android/theme/Theme.kt",
    "swift": "ui/ios/Sources/ShipQuickUI/Tokens.swift",
    "kt_golden": "tests/golden/Theme.kt.golden",
    "swift_golden": "tests/golden/Tokens.swift.golden",
}
GROUPS = {"$description", "color", "typography", "spacing", "shape", "feel"}
RESERVED = set("as break case class continue default defer do else enum extension false for func guard if import in init interface is let "
               "null object package private protocol public return self static struct super switch this throw true try typealias "
               "val var when where while".split())
HEADER = ("GENERATED by scripts/emit_tokens.py from design/tokens.json (story #184). Do not edit.\n"
          "Change the tokens, then run: python3 scripts/emit_tokens.py")
ROLE = {"onSurface": "onSurface and onBackground", "onSurfaceMuted": "onSurfaceVariant", "surface": "surface and its containers"}
IMPACT = {"light", "medium", "heavy", "soft", "rigid"}
NOTICE = {"success", "warning", "error"}


class TokenError(Exception):
    pass


def name(n):
    if not re.fullmatch(r"[a-z][A-Za-z0-9]*", n) or n in RESERVED:
        raise TokenError(f"token name '{n}' is not a safe identifier in Kotlin and Swift")
    return n


def val(node, path):
    if not isinstance(node, dict) or "$value" not in node:
        raise TokenError(f"{path} has no $value")
    return node["$value"]


def leaves(group, path):
    """(name, $value) for every leaf token of a group (a dict of leaf tokens), in file order."""
    return [(name(k), val(v, f"{path}.{k}")) for k, v in group.items() if not k.startswith("$")]


def num(v, unit, path):
    m = re.fullmatch(rf"(\d+(?:\.\d+)?){unit}", str(v))
    if not m:
        raise TokenError(f"{path}: '{v}' must be a number with the unit {unit}")
    return m.group(1)


def rgb(v, path):
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", str(v)):
        raise TokenError(f"{path}: '{v}' must be a #RRGGBB colour")
    return int(v[1:], 16)


def mix(a, b, t):
    """Colour a moved t (0..1) of the way to colour b, per channel, rounded."""
    out = 0
    for shift in (16, 8, 0):
        x, y = (a >> shift) & 255, (b >> shift) & 255
        out |= (x + round((y - x) * t)) << shift
    return out


def dark_of(c):
    bg, fg = c["onSurface"], c["background"]  # swapped
    return {"background": bg, "onSurface": fg, "primary": c["onPrimary"], "onPrimary": c["primary"],
            "surface": mix(bg, fg, 0.06), "onSurfaceMuted": mix(fg, bg, 0.35), "outline": mix(fg, bg, 0.5),
            "error": c["error"], "onError": c["onError"]}


def load(tokens):
    t = json.loads(Path(tokens).read_text(encoding="utf-8"))
    unknown = sorted(set(t) - GROUPS)
    if unknown:
        raise TokenError(f"tokens.json has a group this emitter does not know: {', '.join(unknown)}")
    c = {k: rgb(v, f"color.{k}") for k, v in leaves(t["color"], "color")}
    for k in ("background", "surface", "onSurface", "onSurfaceMuted", "outline", "primary", "onPrimary", "error", "onError"):
        if k not in c:
            raise TokenError(f"color.{k} is missing")
    ty = t["typography"]
    if val(ty["fontFamily"], "typography.fontFamily") != "system-ui":
        raise TokenError("typography.fontFamily must be system-ui (each platform's own system font)")
    size = {k: num(v, "sp", f"typography.size.{k}") for k, v in leaves(ty["size"], "typography.size")}
    weight = {k: int(v) for k, v in leaves(ty["weight"], "typography.weight")}
    for k in ("small", "body", "title", "headline"):
        if k not in size:
            raise TokenError(f"typography.size.{k} is missing")
    for k in ("regular", "medium", "bold"):
        if k not in weight:
            raise TokenError(f"typography.weight.{k} is missing")
    f = t["feel"]
    for k in f:
        if k not in ("$description", "motion", "haptics", "touchTarget"):
            raise TokenError(f"feel.{k} is not known to this emitter")
    mo = f["motion"]
    dur = {k: num(v, "ms", f"feel.motion.duration.{k}") for k, v in leaves(mo["duration"], "feel.motion.duration")}
    ease = {}
    for k, v in leaves(mo["easing"], "feel.motion.easing"):
        if not (isinstance(v, list) and len(v) == 4 and all(isinstance(x, (int, float)) for x in v)):
            raise TokenError(f"feel.motion.easing.{k} must be four numbers")
        ease[k] = v
    hap = {}
    for k, v in leaves({a: b for a, b in f["haptics"].items()}, "feel.haptics"):
        if not (isinstance(v, dict) and set(v) == {"android", "ios"}):
            raise TokenError(f"feel.haptics.{k} needs android and ios")
        if not re.fullmatch(r"[A-Z_]+", v["android"]):
            raise TokenError(f"feel.haptics.{k}.android '{v['android']}' must be a HapticFeedbackConstants name")
        kind, _, style = v["ios"].partition(".")
        if not ((kind == "impact" and style in IMPACT) or (kind == "notification" and style in NOTICE)):
            raise TokenError(f"feel.haptics.{k}.ios '{v['ios']}' must be impact.<{'|'.join(sorted(IMPACT))}> or notification.<{'|'.join(sorted(NOTICE))}>")
        hap[k] = v
    tt = f["touchTarget"]
    touch = {"android": num(val(tt["android"], "feel.touchTarget.android"), "dp", "feel.touchTarget.android"),
             "ios": num(val(tt["ios"], "feel.touchTarget.ios"), "pt", "feel.touchTarget.ios")}
    sp = {k: num(v, "dp", f"spacing.{k}") for k, v in leaves(t["spacing"], "spacing")}
    sh = {k: num(v, "dp", f"shape.{k}") for k, v in leaves(t["shape"], "shape")}
    for k in ("radiusSmall", "radiusMedium", "radiusLarge"):
        if k not in sh:
            raise TokenError(f"shape.{k} is missing")
    return {"color": c, "size": size, "weight": weight, "spacing": sp, "shape": sh, "dur": dur, "ease": ease,
            "haptics": hap, "touch": touch}


def cap(s):
    return s[0].upper() + s[1:]


def kt_color(v):
    return f"Color(0xFF{v:06X})"


def render_kotlin(d):
    c, dk = d["color"], dark_of(d["color"])
    L = [f"// {HEADER.splitlines()[0]}", f"// {HEADER.splitlines()[1]}", "package com.shipquick.ui.theme", "",
         "import android.view.HapticFeedbackConstants",
         "import androidx.compose.animation.core.CubicBezierEasing",
         "import androidx.compose.foundation.isSystemInDarkTheme",
         "import androidx.compose.foundation.shape.RoundedCornerShape",
         "import androidx.compose.material3.ColorScheme",
         "import androidx.compose.material3.MaterialTheme",
         "import androidx.compose.material3.Shapes",
         "import androidx.compose.material3.Typography",
         "import androidx.compose.material3.darkColorScheme",
         "import androidx.compose.material3.lightColorScheme",
         "import androidx.compose.runtime.Composable",
         "import androidx.compose.ui.graphics.Color",
         "import androidx.compose.ui.text.TextStyle",
         "import androidx.compose.ui.text.font.FontFamily",
         "import androidx.compose.ui.text.font.FontWeight",
         "import androidx.compose.ui.unit.dp",
         "import androidx.compose.ui.unit.sp", ""]

    def scheme(fn, k):
        # Every Material 3 role is set, so no baseline purple of Google's default leaks into an app.
        r = lambda n: kt_color(k[n])
        return [f"private val {fn}: ColorScheme = {'dark' if fn.startswith('Dark') else 'light'}ColorScheme(",
                f"    primary = {r('primary')}, onPrimary = {r('onPrimary')},",
                f"    primaryContainer = {r('surface')}, onPrimaryContainer = {r('onSurface')},",
                f"    secondary = {r('primary')}, onSecondary = {r('onPrimary')},",
                f"    secondaryContainer = {r('surface')}, onSecondaryContainer = {r('onSurface')},",
                f"    tertiary = {r('primary')}, onTertiary = {r('onPrimary')},",
                f"    tertiaryContainer = {r('surface')}, onTertiaryContainer = {r('onSurface')},",
                f"    background = {r('background')}, onBackground = {r('onSurface')},",
                f"    surface = {r('surface')}, onSurface = {r('onSurface')},",
                f"    surfaceVariant = {r('surface')}, onSurfaceVariant = {r('onSurfaceMuted')},",
                f"    surfaceTint = {r('primary')},",
                f"    inverseSurface = {r('onSurface')}, inverseOnSurface = {r('background')}, inversePrimary = {r('primary')},",
                f"    error = {r('error')}, onError = {r('onError')},",
                f"    errorContainer = {r('surface')}, onErrorContainer = {r('error')},",
                f"    outline = {r('outline')}, outlineVariant = {r('outline')}, scrim = {r('onSurface')},",
                f"    surfaceBright = {r('surface')}, surfaceDim = {r('surface')},",
                f"    surfaceContainerLowest = {r('background')}, surfaceContainerLow = {r('surface')},",
                f"    surfaceContainer = {r('surface')}, surfaceContainerHigh = {r('surface')}, surfaceContainerHighest = {r('surface')},",
                ")", ""]

    L += ["// Token to Material role: " + ", ".join(f"{k} -> {ROLE.get(k, k)}" for k in c) + ".", ""]
    L += scheme("LightColors", c) + scheme("DarkColors", dk)
    L += ["/** The type sizes of design/tokens.json. */", "object ShipQuickTypeSize {"]
    L += [f"    val {k} = {v}.sp" for k, v in d["size"].items()] + ["}", ""]
    L += ["/** The font weights of design/tokens.json. */", "object ShipQuickFontWeight {"]
    L += [f"    val {k} = FontWeight({v})" for k, v in d["weight"].items()] + ["}", ""]

    def style(size, weight):
        return f"TextStyle(fontFamily = FontFamily.Default, fontSize = ShipQuickTypeSize.{size}, fontWeight = ShipQuickFontWeight.{weight})"

    roles = [("displayLarge", "headline", "bold"), ("displayMedium", "headline", "bold"), ("displaySmall", "headline", "bold"),
             ("headlineLarge", "headline", "bold"), ("headlineMedium", "title", "bold"), ("headlineSmall", "title", "bold"),
             ("titleLarge", "title", "medium"), ("titleMedium", "body", "medium"), ("titleSmall", "small", "medium"),
             ("bodyLarge", "body", "regular"), ("bodyMedium", "body", "regular"), ("bodySmall", "small", "regular"),
             ("labelLarge", "body", "medium"), ("labelMedium", "small", "medium"), ("labelSmall", "small", "medium")]
    L += ["private val ShipQuickTypography = Typography("] + [f"    {r} = {style(s, w)}," for r, s, w in roles] + [")", ""]
    sh = d["shape"]
    L += ["/** The corner radii of design/tokens.json. */", "object ShipQuickShape {"]
    L += [f"    val {k} = RoundedCornerShape({v}.dp)" for k, v in sh.items()] + ["}", ""]
    L += ["private val ShipQuickShapes = Shapes(",
          "    extraSmall = ShipQuickShape.radiusSmall, small = ShipQuickShape.radiusSmall,",
          "    medium = ShipQuickShape.radiusMedium, large = ShipQuickShape.radiusLarge, extraLarge = ShipQuickShape.radiusLarge,", ")", ""]
    L += ["/** The spacing scale of design/tokens.json. */", "object ShipQuickSpacing {"]
    L += [f"    val {k} = {v}.dp" for k, v in d["spacing"].items()] + ["}", ""]
    L += ["/** Feel: how the app moves. Durations are in milliseconds. */", "object ShipQuickMotion {"]
    L += [f"    const val duration{cap(k)}Ms = {v}" for k, v in d["dur"].items()]
    L += [f"    val easing{cap(k)} = CubicBezierEasing({', '.join(str(float(x)) + 'f' for x in v)})" for k, v in d["ease"].items()] + ["}", ""]
    L += ["/** Feel: the one meaning each haptic has, as Android's HapticFeedbackConstants name. */", "object ShipQuickHaptics {"]
    L += [f"    const val {k} = HapticFeedbackConstants.{v['android']}" for k, v in d["haptics"].items()] + ["}", ""]
    L += ["/** Feel: the smallest pressable area (Material: 48dp). */", "object ShipQuickTouchTarget {",
          f"    val min = {d['touch']['android']}.dp", "}", ""]
    L += ["/** The one theme an app wraps its screens in. Brand colours come only through here. */", "@Composable",
          "fun ShipQuickTheme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {",
          "    MaterialTheme(",
          "        colorScheme = if (darkTheme) DarkColors else LightColors,",
          "        typography = ShipQuickTypography,", "        shapes = ShipQuickShapes,", "        content = content,", "    )", "}", ""]
    return "\n".join(L)


def sw_color(v):
    return f"0x{v:06X}"


def render_swift(d):
    c, dk = d["color"], dark_of(d["color"])
    L = [f"// {HEADER.splitlines()[0]}", f"// {HEADER.splitlines()[1]}", "import SwiftUI", "import UIKit", "",
         "private extension Color {",
         "    /// One colour that follows the system light or dark appearance.",
         "    init(light: UInt32, dark: UInt32) {",
         "        func ui(_ v: UInt32) -> UIColor {",
         "            UIColor(red: CGFloat((v >> 16) & 255) / 255, green: CGFloat((v >> 8) & 255) / 255, blue: CGFloat(v & 255) / 255, alpha: 1)",
         "        }",
         "        self.init(UIColor { $0.userInterfaceStyle == .dark ? ui(dark) : ui(light) })",
         "    }", "}", "",
         "/// design/tokens.json as SwiftUI values. dp in the file is pt here.", "public enum ShipQuickTokens {",
         "    public enum Colors {"]
    L += [f"        public static let {k} = Color(light: {sw_color(c[k])}, dark: {sw_color(dk[k])})" for k in c] + ["    }", ""]
    L += ["    // ponytail: fixed point sizes, no Dynamic Type; wrap with @ScaledMetric where an app needs it.", "    public enum TypeSize {"]
    L += [f"        public static let {k}: CGFloat = {v}" for k, v in d["size"].items()] + ["    }", ""]
    wmap = {100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium", 600: "semibold", 700: "bold", 800: "heavy", 900: "black"}
    L += ["    public enum Weight {"]
    for k, v in d["weight"].items():
        if v not in wmap:
            raise TokenError(f"typography.weight.{k}: {v} is not 100 to 900 in steps of 100")
        L.append(f"        public static let {k}: Font.Weight = .{wmap[v]}")
    L += ["    }", "", "    public enum Fonts {"]
    for k in d["size"]:
        for w in d["weight"]:
            L.append(f"        public static let {k}{cap(w)} = Font.system(size: TypeSize.{k}, weight: Weight.{w})")
    L += ["    }", "", "    public enum Spacing {"] + [f"        public static let {k}: CGFloat = {v}" for k, v in d["spacing"].items()]
    L += ["    }", "", "    public enum Radius {"] + [f"        public static let {k}: CGFloat = {v}" for k, v in d["shape"].items()]
    L += ["    }", "", "    /// Feel: how the app moves. Durations are in seconds.", "    public enum Motion {"]
    L += [f"        public static let duration{cap(k)}: Double = {float(v) / 1000:g}" for k, v in d["dur"].items()]
    for k, v in d["ease"].items():
        L.append(f"        public static func {k}(duration: Double = durationMedium) -> Animation {{ .timingCurve({', '.join(str(float(x)) for x in v)}, duration: duration) }}")
    L += ["    }", "", "    /// Feel: the one meaning each haptic has, as UIKit's feedback generators.", "    public enum Haptics {"]
    for k, v in d["haptics"].items():
        kind, _, style = v["ios"].partition(".")
        call = (f"UIImpactFeedbackGenerator(style: .{style}).impactOccurred()" if kind == "impact"
                else f"UINotificationFeedbackGenerator().notificationOccurred(.{style})")
        L += ["        @MainActor", f"        public static func {k}() {{ {call} }}"]
    L += ["    }", "", "    /// Feel: the smallest pressable area (Apple HIG: 44pt).",
          f"    public static let touchTarget: CGFloat = {d['touch']['ios']}", "}", ""]
    return "\n".join(L)


def render(tokens):
    d = load(tokens)
    kt, sw = render_kotlin(d), render_swift(d)
    return {"kt": kt, "swift": sw, "kt_golden": kt, "swift_golden": sw}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--tokens", default=str(KIT / "design" / "tokens.json"))
    ap.add_argument("--out", default=str(KIT))
    a = ap.parse_args(argv)
    try:
        out = render(a.tokens)
    except TokenError as e:
        print(f"emit_tokens: {e}", file=sys.stderr)
        return 2
    root = Path(a.out)
    stale = [FILES[k] for k in FILES if not (root / FILES[k]).is_file() or (root / FILES[k]).read_text(encoding="utf-8") != out[k]]
    if a.check:
        for f in stale:
            print(f"STALE {f}: run python3 scripts/emit_tokens.py", file=sys.stderr)
        return 1 if stale else 0
    for k, f in FILES.items():
        p = root / f
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(out[k], encoding="utf-8")
    print("wrote " + ", ".join(FILES.values()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
