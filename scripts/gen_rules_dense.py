#!/usr/bin/env python3
"""Make plugin/rules-dense.md from CLAUDE.md (story #313, A2, epic #309).

The plugin's hooks inject these ten load-bearing rules into every session and subagent. The
rule numbers below are the ones a helper session must never miss; the text is taken from
CLAUDE.md, so a rule edit flows through here and the drift check in CI turns red until the
generated file is committed.

Usage:
    python3 scripts/gen_rules_dense.py            # write plugin/rules-dense.md
    python3 scripts/gen_rules_dense.py --check    # exit 1 if the committed file is stale
    python3 scripts/gen_rules_dense.py --source X # read rules from X instead of CLAUDE.md
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "plugin" / "rules-dense.md"
RULES = [0, 1, 4, 5, 12, 19, 20, 22, 26, 30]
CAP = 260
LINE = re.compile(r"^(\d+)\. (.*)$")


def dense(text):
    text = text.replace("**", "").replace("`", "")
    for end in re.finditer(r"\.\s", text):
        if 80 <= end.start() + 1 <= CAP:
            text = text[:end.start() + 1]
            break
    if len(text) > CAP:
        text = text[:CAP].rsplit(" ", 1)[0] + " ..."
    return text


def build(source_text):
    found = {}
    for line in source_text.splitlines():
        m = LINE.match(line)
        if m:
            found.setdefault(int(m.group(1)), m.group(2))
    missing = [n for n in RULES if n not in found]
    if missing:
        raise SystemExit(f"rules missing from CLAUDE.md: {missing}")
    lines = ["# ShipQuick rules (dense, generated from CLAUDE.md)", "",
             "Read these every session. Full text: CLAUDE.md. Do not edit this file; run scripts/gen_rules_dense.py.", ""]
    lines += [f"- Rule {n}: {dense(found[n])}" for n in RULES]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--source", default=str(ROOT / "CLAUDE.md"))
    args = ap.parse_args(argv)
    want = build(Path(args.source).read_text(encoding="utf-8"))
    if args.check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != want:
            print(f"plugin/rules-dense.md is stale: run python3 scripts/gen_rules_dense.py and commit it")
            return 1
        print("rules-dense.md OK")
        return 0
    OUT.write_text(want, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
