"""Story #183 (S3, ADR-012): turn each S2 component doc into native reference topics the Astryx CLI serves.

The CLI's `component` command needs a React source file beside every doc (spike, 9 Nov 2026), so Android
and iOS parts are served as topics instead: `ui docs android-button --dense`. The source of truth stays
`ui/components/<Name>/` (checked by check_ui_docs.py); this script only writes `ui/integration/docs/`.
A prop is listed when the contract has it in `core` or under that platform; `webOnly` props never are.
Text is the shared `usage` plus that platform's `platformUsage` only (story #228). A topic that names the other
platform's API (OTHER_API) fails with exit 1, naming the topic and the word.

Usage: python3 scripts/ui_topics.py            write the topics
       python3 scripts/ui_topics.py --check    exit 1 naming each topic that is missing, stale or orphaned
"""
import argparse
import json
import re
import sys
from pathlib import Path

from check_ui_docs import read_doc

KIT = Path(__file__).resolve().parent.parent
SRC = KIT / "ui" / "components"
OUT = KIT / "ui" / "integration" / "docs"
PLATFORMS = {"android": ("Android, Compose Material 3", "Google"), "ios": ("iOS, SwiftUI", "Apple")}
# Story #228: names that belong to the other platform. A topic that holds one fails, so a Swift reader never gets Kotlin.
OTHER_API = {
    "ios": [r"remember[A-Z]\w*", r"Modifier\.", r"@Composable", r"androidx", r"MaterialTheme", r"Scaffold",
            r"LaunchedEffect", r"\b\d+\.?(?:dp|sp)\b", r"onValueChange", r"Material3", r"ModalBottomSheet\(",
            r"mutableStateOf", r"Kotlin"],
    "android": [r"Swift\w*", r"@State", r"@Binding", r"\.sheet\(", r"NavigationStack", r"UIKit",
                r"\.toggleStyle\(", r"@Environment", r"@Observable", r"\.presentationDetents", r"Toggle\(isOn:",
                r"\.alert\(", r"NavigationView", r"\$[a-z]\w*"],
}
HEADER ="/** Generated by scripts/ui_topics.py from ui/components/. Do not edit; edit the source doc. */\n"


def topic(doc, contract, platform):
    label, vendor = PLATFORMS[platform]
    target = doc["platforms"][platform]
    allowed = set(contract.get("core", {})) | set(contract.get("platforms", {}).get(platform, {}))
    props = doc.get("props", [])
    own = {p["name"] for p in props if p.get("platform") == platform}
    rows = [[p["name"], p["type"], p.get("default", ""), p.get("description", "")] for p in props
            if p["name"] in allowed and (p.get("platform") == platform or not p.get("platform") and p["name"] not in own)]
    # Story #228: shared `usage` plus this platform's own `platformUsage` entry, never another platform's.
    shared, mine = doc.get("usage", {}), doc.get("platformUsage", {}).get(platform, {})
    usage = {"description": " ".join(t for t in (shared.get("description", ""), mine.get("description", "")) if t),
             **{k: shared.get(k, []) + mine.get(k, []) for k in ("bestPractices", "accessibility")}}
    practices = usage["bestPractices"]
    # Story #231: this platform's variants and supporting API. A deprecated or unavailable one is only ever a
    # "Do not use" line, never a recommendation.
    api = doc.get("platformApi", {}).get(platform, {})
    items = api.get("variants", []) + api.get("supporting", [])
    ok = [f"{i['name']}: {i.get('note') or i.get('use') or 'own props: ' + ', '.join(p['name'] for p in i.get('props', []))}"
          for i in items if not i.get("status")]
    avoid = [f"Do not use: {i['name']}. Use {i['replacement']}." for i in items if i.get("status")]
    # Story #231: a doc can speak to a platform with no main type of its own (a new iOS doc, a framework topic).
    shown = f"`{target}`" if target else f"the {label.split(', ', 1)[1]} API below"
    lead = (f"Do not use: {target}. Use {doc['replacement']}." if doc.get("status") else
            f"Use {shown} as {vendor} ships it. Never wrap or redraw it. Brand comes from the tokens in design/tokens.json.")
    sections = [
        {"title": "Use", "content": [
            {"type": "prose", "text": lead},
            {"type": "prose", "text": usage["description"]},
        ]},
        {"title": "Props", "content": [{"type": "table", "headers": ["Prop", "Type", "Default", "Description"], "rows": rows}]},
        {"title": "Variants and supporting API", "content": [
            {"type": "list", "style": "unordered", "items": ok},
            {"type": "list", "style": "dont", "items": avoid},
        ]},
        {"title": "Do and do not", "content": [
            {"type": "list", "style": "do", "items": [b["description"] for b in practices if b.get("guidance")]},
            {"type": "list", "style": "dont", "items": [b["description"] for b in practices if not b.get("guidance")]},
        ]},
        {"title": "Accessibility", "content": [{"type": "list", "style": "unordered", "items": [
            f"{a['name']} ({a.get('criterion', '')}, {a.get('requirement', '')}): {a.get('description', '')}"
            for a in usage["accessibility"]]}]},
    ]
    # The CLI refuses an empty list or table (CI on PR #209), so drop empty blocks (prose too), then empty sections.
    for s in sections:
        s["content"] = [b for b in s["content"] if b.get("items", b.get("rows", b.get("text", "").strip()))]
    sections = [s for s in sections if s["content"]]
    return {"type": "generic", "name": f"{platform}-{doc['name'].lower()}",
            "title": f"{doc.get('displayName', doc['name'])} ({label})", "category": "guide",
            "description": f"{target or doc.get('displayName', doc['name'])} used directly: the ShipQuick contract, props, do and do not.",
            "keywords": [*doc.get("keywords", []), platform], "sections": sections}


def leaks(t, platform):
    """One line per other-platform API name found in topic `t` (story #228)."""
    text = json.dumps(t, ensure_ascii=False)
    return [f"leak in {t['name']}: '{m.group(0)}' is the other platform's API, not {platform}'s; "
            "move that text to platformUsage.<its platform>"
            for p in OTHER_API[platform] for m in re.finditer(p, text)]


def speaks_to(doc, platform):
    """Story #231: a doc has a topic for a platform when it names that platform's main type, or lists API or usage
    for it. A new iOS doc cannot set platforms.ios (the gate counts only HIG rows there), so it uses platformApi."""
    return any(doc.get(k, {}).get(platform) for k in ("platforms", "platformApi", "platformUsage"))


def render(src=SRC):
    """({file name: file text} for every topic the sources ask for, [leak lines])."""
    files, bad, owner = {}, [], {}
    for folder in sorted(p for p in src.iterdir() if p.is_dir()) if src.is_dir() else []:
        doc = read_doc(folder / f"{folder.name}.doc.mjs")
        contract = json.loads((folder / f"{folder.name}.contract.json").read_text(encoding="utf-8"))
        for platform in PLATFORMS:
            if speaks_to(doc, platform):
                t = topic(doc, contract, platform)
                bad += leaks(t, platform)
                # Two docs writing one topic file would hide one of them (PR #255 follow-up).
                if t["name"] in owner:
                    bad.append(f"clash: {t['name']} comes from both {owner[t['name']]} and {folder.name}; give each doc its own name")
                owner[t["name"]] = folder.name
                files[f"{t['name']}.doc.mjs"] = HEADER + "export default " + json.dumps(t, indent=2, ensure_ascii=False) + ";\n"
    return files, bad


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", type=Path, default=SRC, help="folder with one subfolder per component")
    a = ap.parse_args(argv)
    if a.root.resolve() != SRC and not a.check:
        ap.error("--root works only with --check; topics are written from ui/components only")
    want, bad = render(a.root)
    if bad:
        for b in bad:
            print(f"ui topics: {b}")
        print(f"{len(bad)} problem(s): a topic names another platform's API, or two docs share a topic name")
        return 1
    have = {p.name: p.read_text(encoding="utf-8") for p in OUT.glob("*.doc.mjs")} if OUT.is_dir() else {}
    if a.check:
        bad = [f"missing {n}" for n in want if n not in have] + [f"stale {n}" for n in want if n in have and have[n] != want[n]] \
            + [f"orphan {n} (no source doc)" for n in have if n not in want]
        for b in bad:
            print(f"ui topics: {b}; run python3 scripts/ui_topics.py")
        print("ui topics OK" if not bad else f"{len(bad)} topic file(s) out of date")
        return 1 if bad else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n in have.keys() - want.keys():
        (OUT / n).unlink()
    for n, text in want.items():
        (OUT / n).write_text(text, encoding="utf-8")
    print(f"wrote {len(want)} topic(s) to {OUT.relative_to(KIT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
