#!/usr/bin/env python3
"""UI coverage gate (story #216, rule 38). Stdlib only.

Reads the two counted lists, docs/research/android-m3-components.md and docs/research/ios-swiftui-components.md.
Fails when: a Count line does not equal its table rows; a row has no doc or contract in ui/components/<Name>/;
a row's doc leaves that platform null (or names a type no row names); two Android rows share a folder; a row has
no `android-<name>` or `ios-<name>` topic in ui/integration/docs/; a doc sets a platform that no row names (extra).
An iOS row maps to its doc by "Our doc" (iOS-only) or by its M3 twin's folder in the Android list (shared).
Rows must run 1 to N; a missing list file is a FAIL line. A doc that several rows share must match ROW_MAP row
for row, so deleting a row (and lowering Count) still fails.
Web: when ui/tool/node_modules/@astryxdesign/core exists, a name our integration serves (a topic, or a component it
registers, as a literal list only) must not equal a core doc name, case and dashes ignored. Core with no docs, or
fewer than --core-floor (100), fails. Without core it prints a skip and passes, unless --require-web (CI) is given.
API lists (story #231): docs/research/android-m3-api.md and ios-swiftui-api.md, generated by scripts/ui_api_lists.py.
A component, variant or modifier row is covered by a doc whose `platforms` names it, or that lists it under
`platformApi.<platform>.variants`; a supporting row by `platformApi.<platform>.supporting`. Gaps print as GAP lines,
one per family, and fail only with --strict-api. CI (job ui-cli) and check_local.sh pass --strict-api: every row is covered.
On iOS (story #285) a component or modifier row counts only for a doc of its Doc family column (the family of the doc's
platforms.ios row, or its platformApi.ios family, a label that one doc sets and some row names).
On Android a component row counts only for a doc of its own family (its main row's family or platformApi family), and
a doc whose platforms.android is a component row of the API list is not an extra (PR #255 review 2). Each slot names
rows of its own kind only.
Framework topics (story #231): each row of docs/research/framework-topics.md is one doc, ui/components/<topic-slug>/
("Swift Charts" -> swift-charts), that speaks to its platform (platformApi or platformUsage) and is served as the topic
<platform>-<topic-slug>. A missing one is a GAP line like an API row. Its platformApi items name the framework's own
types, which are not rows of the API lists, so only a framework doc may name them, and only names of the saved
framework list docs/research/sources/framework-names.json (story #288), pinned by sha256 in framework-topics.md.
usage: check_ui_coverage.py [--require-web] [--strict-api]
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

from check_ui_docs import read_doc

KIT = Path(__file__).resolve().parent.parent
CORE = KIT / "ui" / "tool" / "node_modules" / "@astryxdesign" / "core"
IOS_ONLY = "none (iOS-only)"
CORE_FLOOR = 100   # core 0.7.11 has 254 *.doc.mjs under src/; far fewer means its layout moved
# A doc that several rows share holds one name, so this map is what makes each of its rows count.
# Deleting a row from a list means editing this protected file too (rule 37), so it is never silent.
# Each row is named by its HIG component (column 2), since two Menu rows share the type SwiftUI.Menu.
ROW_MAP = {"ios": {
    "Menu": ["Context menus", "Menus", "Pop-up buttons", "Pull-down buttons"],
    "BottomSheet": ["Action sheets", "Sheets"],
    "TextField": ["Text fields", "Virtual keyboards"],
}}


def table(path, label):
    """(numbered table rows as cell lists, errors). Rows must run 1 to N, and N must equal the Count line."""
    if not path.is_file():
        return [], [f"{label} list: file not found: {path}"]
    text = path.read_text(encoding="utf-8")
    m = re.search(r"^Count: (\d+)$", text, re.M)
    rows = [cells for line in text.splitlines() if line.startswith("|")
            for cells in [[c.strip() for c in line.strip().strip("|").split("|")]] if cells[0].isdigit()]
    errs = []
    n = int(m.group(1)) if m else None
    if n != len(rows):
        errs.append(f"{label} list: Count line says {n}, the table has {len(rows)} rows")
    nums = [int(r[0]) for r in rows]
    if nums != list(range(1, len(rows) + 1)):
        errs.append(f"{label} list: row numbers must run 1 to {len(rows)} with no gap or repeat, got {nums}")
    return rows, errs


# Only `components: ['A', "B"]`; a variable or a call there would hide what is served.
LITERAL_LIST = re.compile(r"""\bcomponents\s*:\s*\[\s*(?:(['"])[^'"]*\1\s*,?\s*)*\]""")


def slug(topic):
    return re.sub(r"[^a-z0-9]+", "-", topic.lower()).strip("-")


def framework_topics(path):
    """({platform: [topic]}, errors) from the `## iOS` and `## Android` tables of framework-topics.md."""
    if not path.is_file():
        return {}, [f"framework topics list: file not found: {path}"]
    out, plat = {}, None
    for line in path.read_text(encoding="utf-8").splitlines():
        if m := re.match(r"^## (iOS|Android)\s*$", line):
            plat = m.group(1).lower()
            out.setdefault(plat, [])
        elif plat and line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells[0].isdigit():
                out[plat].append(cells[1])
    return out, []


def framework_names(names_path, topics_path):
    """({platform: set of qualified names}, errors) from the saved framework names (story #288), which must match the
    sha256 framework-topics.md pins, so an edit by hand fails."""
    if not names_path.is_file():
        return {}, [f"{names_path.name}: file not found: {names_path}; run python3 scripts/ui_api_lists.py --fetch-frameworks"]
    raw = names_path.read_bytes()
    text = topics_path.read_text(encoding="utf-8") if topics_path.is_file() else ""
    pin = re.search(rf"^Saved names: `docs/research/sources/{re.escape(names_path.name)}` sha256 `([0-9a-f]{{64}})`$", text, re.M)
    if not pin or pin.group(1) != hashlib.sha256(raw).hexdigest():
        return {}, [f"{names_path.name}: its sha256 does not match the pin in {topics_path.name}; "
                    "run python3 scripts/ui_api_lists.py --fetch-frameworks, never edit it by hand"]
    out = {}
    for p in json.loads(raw)["packages"]:
        out.setdefault(p["platform"], set()).update(p["names"])
    return out, []


def known(name, names):
    """A doc name is known when a saved qualified name is it or ends with it after a dot (`Charts.BarMark`)."""
    return name in names or any(n.endswith("." + name) for n in names)


def api_gaps(a, docs, api, status, errs, frameworks=None, usage=None, fw_names=None):
    """Lines naming, per platform and family, the API list rows no doc covers. A row is covered only by a structured
    field of exactly one doc: `platforms.<p>` (the doc's main API, with the doc-level `status`), an object in
    `platformApi.<p>.variants` or `.supporting`, or `platformApi.<p>.family` for a family row. A covering entry
    carries the row's status. Errors (always fail): an unreadable list, a string item, a name the list does not
    have, and a row two docs claim."""
    gaps = []
    for platform, path in (("android", a.android_api), ("ios", a.ios_api)):
        rows, e = table(path, f"{platform} API")
        errs += e
        claims = {}   # (slot, name) -> [(doc, status)]; slot is main, variants, supporting or family
        ios_fams = {}   # story #285: iOS family -> [docs]; an iOS family is a label, not a row
        topics = (frameworks or {}).get(platform, [])
        fw_docs = {slug(t) for t in topics}
        for doc, plats in docs.items():
            if plats.get(platform):
                claims.setdefault(("main", plats[platform]), []).append((doc, status.get(doc) or "-"))
            mine = api[doc].get(platform, {})
            if mine.get("family") and platform == "ios":
                ios_fams.setdefault(mine["family"], []).append(doc)
            elif mine.get("family"):
                claims.setdefault(("family", mine["family"]), []).append((doc, "-"))
            for slot in ("variants", "supporting"):
                for item in mine.get(slot, []):
                    if not isinstance(item, dict):
                        errs.append(f"api {platform} {doc}: platformApi.{platform}.{slot} item {item!r} must be an object")
                        continue
                    claims.setdefault((slot, item["name"]), []).append((doc, item.get("status") or "-"))
        # PR #255 review 2: each slot names rows of its own kind only, so a supporting entry cannot name a variant row.
        of_kind = {"variants": {r[1].strip("`") for r in rows if r[2] not in ("supporting", "family")},
                   "supporting": {r[1].strip("`") for r in rows if r[2] == "supporting"},
                   "family": {r[1].strip("`") for r in rows if r[2] == "family"}}
        word = {"variants": "variant", "supporting": "supporting", "family": "family"}
        any_row = set().union(*of_kind.values())
        for (slot, n), who in sorted(claims.items()):
            if n not in any_row and slot in of_kind:
                # Review 2 of the iOS stack: only a framework doc, and only for a name that is no row at all (its
                # framework's own type), skips this check. A real row in the wrong slot still fails. Story #288: that
                # name must be in the saved framework names of this platform, so a typo fails.
                fw_bad = [w for w in who if w[0] in fw_docs and not known(n, (fw_names or {}).get(platform, set()))]
                if fw_bad:
                    errs.append(f"api {platform}: {', '.join(d for d, _ in fw_bad)} names {n} under platformApi.{platform}.{slot}, "
                                f"but neither the {platform} API list nor the saved framework names (framework-names.json) have it")
                who = [w for w in who if w[0] not in fw_docs]
                if not who:
                    continue
            if slot in of_kind and n not in of_kind[slot]:
                errs.append(f"api {platform}: {', '.join(d for d, _ in who)} names {n} under platformApi.{platform}.{slot}, "
                            f"but the {platform} API list has no such {word[slot]} row")
        # Own family (Android: PR #255 review 2; iOS: story #285). A row of a checked kind is covered only by a doc of
        # its family, through its main API or its variants. A doc's families are the family of the row its platforms
        # name points to, and its platformApi family. Android checks component rows, by the Family column. iOS checks
        # component and modifier rows, by the Doc family column the generator writes (a modifier's Apple page, or the
        # control doc the list maps it to, as `.sheet` to BottomSheet).
        if platform == "android":
            checked = ("component",)
            need_of = {r[1].strip("`"): r[4] for r in rows}
            fam_of = {f"{r[5].strip('`')}.{r[1].strip('`')}": r[4] for r in rows if r[2] in ("component", "variant")}
        else:
            checked = ("component", "modifier")
            if any(len(r) < 11 for r in rows):
                errs.append("ios API list: no Doc family column; run python3 scripts/ui_api_lists.py")
            errs += [f"ios API list: row {r[0]} ({r[1].strip('`')}): Doc family is empty" for r in rows if len(r) > 10 and not r[10]]
            need_of = {r[1].strip("`"): r[10] if len(r) > 10 else r[4] for r in rows}
            fam_of = {f"SwiftUI.{r[1].strip('`')}": need_of[r[1].strip("`")] for r in rows if r[2] in checked}
            for fam, ds in sorted(ios_fams.items()):
                if len(ds) > 1:
                    errs.append(f"api ios: {len(ds)} docs set platformApi.ios.family {fam} ({', '.join(ds)}); a family has one doc")
                if fam not in set(need_of.values()):
                    errs.append(f"api ios: {', '.join(ds)} sets platformApi.ios.family {fam}, but no row of the ios API list "
                                "has that Doc family")
        doc_fams = {d: {fam_of.get(p.get(platform)), api[d].get(platform, {}).get("family")} for d, p in docs.items()}
        by_family = {}
        for r in rows:
            name, kind, family = r[1].strip("`"), r[2], r[4]
            want = r[7] if len(r) > 7 else "-"
            full = f"{r[5].strip('`')}.{name}" if platform == "android" else f"SwiftUI.{name}"
            slots = {"family": [("family", name)], "supporting": [("supporting", name)]}.get(kind, [("main", full), ("variants", name)])
            owners = [o for s in slots for o in claims.get(s, [])]
            if kind in checked and len(owners) == 1 and need_of[name] not in doc_fams[owners[0][0]]:
                by_family.setdefault(family, []).append(f"{name} ({kind}, needs a doc of family {need_of[name]})")
            elif len(owners) > 1:
                errs.append(f"api {platform} {name}: {len(owners)} docs claim this row ({', '.join(d for d, _ in owners)}); "
                            "a row has one owner")
            elif not owners:
                by_family.setdefault(family, []).append(f"{name} ({kind})")
            elif owners[0][1] != want:
                by_family.setdefault(family, []).append(f"{name} ({kind}, needs status {want})")
        for t in topics:
            d = slug(t)
            speaks = d in docs and (api[d].get(platform) or (usage or {}).get(d, {}).get(platform))
            served = a.topics / f"{platform}-{d}.doc.mjs"
            if not speaks or not served.is_file() or not served.read_text(encoding="utf-8").strip():   # an empty file serves nothing
                by_family.setdefault("framework topics", []).append(f"{t} (framework)")
        gaps += [f"api {platform} {fam}: " + ", ".join(names) for fam, names in sorted(by_family.items())]
    return gaps


def key(name):
    return re.sub(r"[-_]", "", name).lower()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--android-list", type=Path, default=KIT / "docs" / "research" / "android-m3-components.md")
    ap.add_argument("--ios-list", type=Path, default=KIT / "docs" / "research" / "ios-swiftui-components.md")
    ap.add_argument("--components", type=Path, default=KIT / "ui" / "components")
    ap.add_argument("--topics", type=Path, default=KIT / "ui" / "integration" / "docs")
    ap.add_argument("--integration", type=Path, default=KIT / "ui" / "integration" / "astryx.integration.mjs")
    ap.add_argument("--core", type=Path, default=CORE)
    ap.add_argument("--require-web", action="store_true", help="fail when core is not installed (CI)")
    ap.add_argument("--core-floor", type=int, default=CORE_FLOOR, help="fewest core docs that count as a real install")
    ap.add_argument("--row-map", type=Path, help="JSON {platform: {doc: [types]}} in place of ROW_MAP (tests)")
    ap.add_argument("--android-api", type=Path, default=KIT / "docs" / "research" / "android-m3-api.md")
    ap.add_argument("--ios-api", type=Path, default=KIT / "docs" / "research" / "ios-swiftui-api.md")
    ap.add_argument("--strict-api", action="store_true", help="fail on every API list row no doc covers")
    ap.add_argument("--frameworks", type=Path, default=KIT / "docs" / "research" / "framework-topics.md")
    ap.add_argument("--framework-names", type=Path, default=KIT / "docs" / "research" / "sources" / "framework-names.json")
    a = ap.parse_args(argv)
    errs = []

    docs, api, status, usage = {}, {}, {}, {}
    for folder in sorted(p for p in a.components.iterdir() if p.is_dir()) if a.components.is_dir() else []:
        d, c = folder / f"{folder.name}.doc.mjs", folder / f"{folder.name}.contract.json"
        if d.exists() and c.exists():
            doc = read_doc(d)
            docs[folder.name], api[folder.name], status[folder.name] = doc.get("platforms", {}), doc.get("platformApi", {}), doc.get("status")
            usage[folder.name] = doc.get("platformUsage", {})

    android_rows, e1 = table(a.android_list, "Android")
    ios_rows, e2 = table(a.ios_list, "iOS")
    errs += e1 + e2
    row_map = json.loads(a.row_map.read_text(encoding="utf-8")) if a.row_map else ROW_MAP

    # platform -> {doc name: set of types its rows name}
    want = {"android": {}, "ios": {}}
    m3_folder, ios_rows_of = {}, {}
    for r in android_rows:
        name = r[2].strip("`").rstrip("/").rsplit("/", 1)[-1]
        if name in want["android"]:
            errs.append(f"Android row {r[0]} ({r[1]}): folder {name} is already used by another row")
        want["android"].setdefault(name, set()).add(r[3].strip("`"))
        m3_folder[r[1]] = name
    for r in ios_rows:
        name = r[6].strip("`") if r[5] == IOS_ONLY else m3_folder.get(r[5])
        if not name:
            errs.append(f"iOS row {r[0]} ({r[1]}): its M3 twin '{r[5]}' is not a row of the Android list")
            continue
        want["ios"].setdefault(name, set()).add(r[2].strip("`"))
        ios_rows_of.setdefault(name, []).append(r[1])
    mapped = row_map.get("ios", {})
    for name in sorted(set(mapped) | {n for n, rs in ios_rows_of.items() if len(rs) > 1}):
        have, need = set(ios_rows_of.get(name, [])), set(mapped.get(name, []))
        if name not in mapped:
            errs.append(f"ios {name}: {len(have)} rows share this doc, but the row map (ROW_MAP) does not list them: {sorted(have)}")
        elif have != need:
            errs.append(f"ios {name}: the row map lists {sorted(need - have)} missing from the list"
                        + (f", and the list has {sorted(have - need)} not in the row map" if have - need else ""))

    # Android only: the iOS card list keeps its cap until the iOS lane decides the same.
    api_main = {"ios": set(), "android": {f"{r[5].strip('`')}.{r[1].strip('`')}"
                                          for r in table(a.android_api, "android")[0] if r[2] == "component"}}
    for platform, names in want.items():
        for name, types in names.items():
            if name not in docs:
                errs.append(f"{platform} {name}: missing doc or contract in {a.components / name}")
                continue
            got = docs[name].get(platform)
            if not got:
                errs.append(f"{platform} {name}: platforms.{platform} is not set (rows name {', '.join(sorted(types))})")
            elif got not in types:
                errs.append(f"{platform} {name}: platforms.{platform} is {got}, but its rows name {', '.join(sorted(types))}")
            if not (a.topics / f"{platform}-{name.lower()}.doc.mjs").exists():
                errs.append(f"{platform} {name}: missing topic {platform}-{name.lower()}; run python3 scripts/ui_topics.py")
        # PR #255 review 2: the generated API list is the source of truth. A doc whose name is a component row there is
        # not an extra; the counted card list stays a check that every card is covered, never a cap.
        errs += [f"{platform} {name}: extra, platforms.{platform} is set but no card row and no component row of the API list names it"
                 for name, plat in docs.items() if plat.get(platform) and name not in names and plat[platform] not in api_main[platform]]

    text = a.integration.read_text(encoding="utf-8") if a.integration.exists() else ""
    served = [p.name[:-len(".doc.mjs")] for p in a.topics.glob("*.doc.mjs")] if a.topics.is_dir() else []
    for m in re.finditer(r"\bcomponents\s*:", text):
        lit = LITERAL_LIST.match(text, m.start())
        if not lit:
            errs.append(f"web: {a.integration.name} sets components to something other than a literal list of names")
            continue
        served += [q[1:-1] for q in re.findall(r"'[^']*'|\"[^\"]*\"", lit.group(0))]
    if a.core.is_dir():
        core = {key(p.name[:-len(".doc.mjs")]): p.name[:-len(".doc.mjs")] for p in (a.core / "src").rglob("*.doc.mjs")}
        if not core:
            errs.append(f"web: no core docs found under {a.core / 'src'}; reinstall with npm ci --ignore-scripts in ui/tool")
        elif len(core) < a.core_floor:
            errs.append(f"web: only {len(core)} core docs under {a.core / 'src'}, below the floor of {a.core_floor}; did core's layout change?")
        errs +=[f"web: our name '{s}' shadows core's '{core[key(s)]}'; rename it" for s in served if key(s) in core]
    elif a.require_web:
        errs.append(f"web: core not found at {a.core}; run npm ci --ignore-scripts in ui/tool")
    else:
        print("skip web: run npm ci --ignore-scripts in ui/tool")

    frameworks, e = framework_topics(a.frameworks)
    errs += e
    fw_names, e = framework_names(a.framework_names, a.frameworks)
    errs += e
    gaps = api_gaps(a, docs, api, status, errs, frameworks, usage, fw_names)
    if a.strict_api:
        errs += gaps   # printed once below, as FAIL lines
    else:
        for g in gaps:
            print("GAP", g)
        if gaps:
            print(f"GAP total: {sum(g.count(' (') for g in gaps)} API rows have no doc yet; --strict-api fails on them")
    for e in errs:
        print("FAIL", e)
    if errs:
        return 1
    print(f"OK: {len(android_rows)} Android and {len(ios_rows)} iOS rows covered, {len(docs)} docs, no extra")
    return 0


if __name__ == "__main__":
    sys.exit(main())
